/**
 * Hash a string to a 32-bit unsigned integer seed
 */
export function hashStringToSeed(str: string): number {
  let hash = 0;
  const clean = (str || "").toLowerCase().trim();
  for (let i = 0; i < clean.length; i++) {
    hash = (hash * 31 + clean.charCodeAt(i)) >>> 0;
  }
  return hash || 1;
}

/**
 * Mulberry32 deterministic PRNG shuffle
 */
export function seededShuffle<T>(array: T[], seed: number): T[] {
  const result = array.slice();
  let state = seed;
  const next = () => {
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(next() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

/**
 * Filters words strictly between minLen (3) and maxLen (8) letters (pure A-Z letters only)
 * and sorts them prioritizing shortest words first (3-letter, 4-letter, 5-letter, etc.)
 */
export function filterAndSortShortestFirst(words: string[]): string[] {
  const set = new Set<string>();
  for (const raw of words) {
    const clean = raw
      .toUpperCase()
      .trim()
      .replace(/[^A-Z]/g, "");
    if (clean.length >= 3 && clean.length <= 8) {
      set.add(clean);
    }
  }
  const result = Array.from(set);
  result.sort((a, b) => a.length - b.length || a.localeCompare(b));
  return result;
}

/**
 * Smart Semantic Theme Matcher
 * Finds the closest ThemeDictionary by matching key, display name, keywords, or token stems.
 */
export function matchSmartTheme(themeText: string): ThemeDictionary | null {
  const clean = (themeText || "").toLowerCase().trim();
  if (!clean) return null;

  // 1. Direct key or display name exact/contains match
  for (const dict of Object.values(SMART_THEME_DICTIONARIES)) {
    const dictName = dict.name.toLowerCase();
    if (clean === dict.key || clean === dictName || clean.includes(dict.key) || clean.includes(dictName) || dictName.includes(clean)) {
      return dict;
    }
  }

  // 2. Keyword exact or substring match
  const tokens = clean.split(/[\s,._-]+/).filter((t) => t.length >= 2);
  let bestMatch: ThemeDictionary | null = null;
  let bestScore = 0;

  for (const dict of Object.values(SMART_THEME_DICTIONARIES)) {
    let score = 0;
    for (const kw of dict.keywords) {
      if (clean.includes(kw)) {
        score += 3;
      }
      for (const tok of tokens) {
        if (tok === kw || tok.startsWith(kw) || kw.startsWith(tok)) {
          score += 2;
        }
      }
    }
    if (score > bestScore) {
      bestScore = score;
      bestMatch = dict;
    }
  }

  if (bestScore >= 2 && bestMatch) {
    return bestMatch;
  }

  return null;
}

/**
 * Builds a theme word list that GUARANTEES:
 * 1. Strictly 3-8 letters only (excluding any words with 9 or more letters to fit 8x8 board)
 * 2. Prioritizes the shortest words first (3 letters, then 4, 5, 6, 7, 8)
 * 3. Strictly includes theme-relevant words first, topped up with generic words if needed
 * 4. Never returns empty or under-sized lists.
 */
export function buildThemeWordList(
  themeText: string,
  existingWords: string[] = [],
  count: number = 50
): string[] {
  const matched = matchSmartTheme(themeText);
  const existingSet = new Set(
    (existingWords || []).map((w) => w.toUpperCase().trim().replace(/[^A-Z]/g, ""))
  );

  // Filter and sort primary theme words by length ascending (shortest first)
  const primaryClean = matched ? filterAndSortShortestFirst(matched.words) : [];
  // Also filter and sort generic words by length ascending
  const seed = hashStringToSeed(themeText || "default");
  const genericClean = filterAndSortShortestFirst(seededShuffle(EXPANDED_GENERIC_WORDS, seed));

  // Available words not already used
  const availablePrimary = primaryClean.filter((w) => !existingSet.has(w));
  const availableGeneric = genericClean.filter(
    (w) => !existingSet.has(w) && !primaryClean.includes(w)
  );

  // Always prioritize PRIMARY theme words first.
  // Within primary words, they are strictly sorted shortest first (3 letters up to 8 letters).
  // Only if primary words are fewer than count, top up from generic words (also shortest first).
  const result: string[] = [];

  for (const w of availablePrimary) {
    if (result.length < count) {
      result.push(w);
    }
  }

  if (result.length < count) {
    for (const w of availableGeneric) {
      if (result.length < count) {
        result.push(w);
      }
    }
  }

  // Fallback top-up if needed
  if (result.length < count) {
    for (const w of [...primaryClean, ...genericClean]) {
      if (!result.includes(w) && result.length < count) {
        result.push(w);
      }
    }
  }

  return result;
}
